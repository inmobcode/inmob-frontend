// Writes src/messages/<locale>/index.ts for every language: it spreads the JSON
// files Spanish has (each one holds whole top-level namespaces). Run after adding a namespace: npm run i18n:index
import { mkdirSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("../src/messages/", import.meta.url).pathname;
const LOCALES = ["es", "en", "pt", "fr", "de", "it", "el", "hr"];
const namespaces = readdirSync(join(ROOT, "es"))
  .filter((file) => file.endsWith(".json"))
  .map((file) => file.slice(0, -5))
  .sort();

const ident = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

for (const locale of LOCALES) {
  const dir = join(ROOT, locale);
  mkdirSync(dir, { recursive: true });
  const present = namespaces.filter((ns) => existsSync(join(dir, `${ns}.json`)));
  const lines = [
    "// Generated by scripts/i18n-index.mjs. Do not edit by hand.",
    ...present.map((ns) => `import ${ident(ns)} from "./${ns}.json";`),
    "",
    // Each file holds whole top-level namespaces; the files only split them up.
    `const messages = { ${present.map((ns) => `...${ident(ns)}`).join(", ")} };`,
    "",
    "export default messages;",
    "",
  ];
  writeFileSync(join(dir, "index.ts"), lines.join("\n"));
}
console.log(`${namespaces.length} namespaces: ${namespaces.join(", ")}`);
